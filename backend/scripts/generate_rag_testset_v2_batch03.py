def assign_ids(pairs: list[tuple[dict, dict]]) -> list[tuple[dict, dict]]:
    for index, (public_case, answer_item) in enumerate(pairs, start=1):
        question_id = f"V2-B03-Q{index:03d}"
        public_case["id"] = question_id
        answer_item["id"] = question_id
    return pairs


def write_json(path: Path, payload: dict) -> None:
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def update_plan_status() -> None:
    if not PLAN_PATH.exists():
        return
    text = PLAN_PATH.read_text(encoding="utf-8")
    lines = []
    for line in text.splitlines():
        if line.startswith("| batch03 |"):
            parts = line.split("|")
            if len(parts) >= 8:
                parts[-2] = " 已生成 "
                line = "|".join(parts)
        lines.append(line)
    text = "\n".join(lines) + ("\n" if text.endswith("\n") else "")
    PLAN_PATH.write_text(text, encoding="utf-8")


def main() -> None:
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    pairs = assign_ids([*pesticide_cases(), *veterinary_cases()])
    cases = [item[0] for item in pairs]
    answers = [item[1] for item in pairs]

    if len(cases) != 75:
        raise RuntimeError(f"batch03 should contain 75 cases, got {len(cases)}")
    doc_counts = Counter(tuple(case["document_ids"]) for case in cases)
    if doc_counts[(DOC_2763_1,)] != 45 or doc_counts[(DOC_31650_1,)] != 30:
        raise RuntimeError(f"unexpected document distribution: {dict(doc_counts)}")

    difficulty_counter = Counter(case["tags"][-1] for case in cases)
    type_counter = Counter(case["tags"][-2] for case in cases)
    document_counter = Counter(str(case["document_ids"][0]) for case in cases)

    batch_payload = {
        "name": "rag-testset-v2-batch03-pesticide-veterinary",
        "cases": cases,
    }
    answer_payload = {
        "name": "rag-testset-v2-batch03-pesticide-veterinary-answer-key",
        "version": "v2.0-batch03",
        "created": date.today().isoformat(),
        "description": "Batch03 covers GB 2763.1 pesticide MRL and GB 31650.1 veterinary drug MRL questions. It is generated offline from current indexed chunks and does not call the RAG API.",
        "total_questions": len(answers),
        "difficulty_distribution": dict(sorted(difficulty_counter.items())),
        "type_distribution": dict(sorted(type_counter.items())),
        "document_distribution": dict(sorted(document_counter.items())),
        "questions": answers,
    }
    report = "\n".join(
        [
            "# RAG 测试集 v2 batch03 生成报告",
            "",
            f"- 生成日期：{date.today().isoformat()}",
            f"- 测试集文件：`{BATCH_PATH.name}`",
            f"- 答案键文件：`{ANSWER_KEY_PATH.name}`",
            f"- 总题量：{len(cases)}",
            f"- 文档分布：GB 2763.1={doc_counts[(DOC_2763_1,)]}，GB 31650.1={doc_counts[(DOC_31650_1,)]}",
            f"- 难度分布：{dict(sorted(difficulty_counter.items()))}",
            f"- 类型分布：{dict(sorted(type_counter.items()))}",
            "",
            "## 说明",
            "",
            "- 本批次不调用 RAG 问答接口，只构建离线评测数据。",
            "- GB 2763.1 的题目优先选择 OCR 中较清晰的 ADI、残留物、检测方法和表格数值。",
            "- GB 31650.1 的题目主要来自 LLM 归一化切块，部分单位在源切块中带有待核验提示，评测答案统一按当前归一化结果记录为 μg/kg。",
            "- citation 关键词仅强制匹配标准号，避免 OCR/归一化切块缺少稳定表号 metadata 时造成误判。",
            "",
        ]
    )

    write_json(BATCH_PATH, batch_payload)
    write_json(ANSWER_KEY_PATH, answer_payload)
    REPORT_PATH.write_text(report, encoding="utf-8")
    update_plan_status()

    print(f"Generated {len(cases)} batch03 cases")
    print(f"Saved: {BATCH_PATH}")
    print(f"Saved: {ANSWER_KEY_PATH}")
    print(f"Saved: {REPORT_PATH}")


